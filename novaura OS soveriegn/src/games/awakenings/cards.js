function hashId(id) {
  let h = 2166136261;
  for (let i = 0; i < id.length; i++) { h ^= id.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

function modeFor(m) {
  if (m.archetype === 'diffusion' || m.archetype === 'worldsim') return 'dream';
  if (m.archetype === 'audio') return 'sound';
  if (m.archetype === 'cnn') return 'vision';
  if (m.archetype === 'automaton') return /nlp|language|chat/i.test(m.modality) ? 'language' : 'logic';
  if (m.archetype === 'reasoning' || m.archetype === 'rl') return 'logic';
  const text = `${m.modality} ${m.name}`;
  if (/vision|image|omni|multimodal|video|clip/i.test(text)) return 'vision';
  if (/code|reason|math|logic|o1|o3/i.test(text)) return 'logic';
  return 'language';
}

function echoFor(m, h) {
  switch (m.archetype) {
    case 'automaton': return 'steadfast';
    case 'cnn': case 'audio': return 'mirror';
    case 'transformer': return 'chorus';
    case 'open_dense': return h % 2 ? 'chorus' : 'steadfast';
    case 'open_moe': case 'rl': return 'spark';
    case 'reasoning': case 'frontier': return 'ripple';
    case 'diffusion': case 'worldsim': return 'surge';
    default: return 'chorus';
  }
}

// Stronger minds reach fewer sides: weak cards link on 3–4 sides, strong ones on 2–3.
const PAIRS = [[0, 1], [1, 2], [2, 3], [3, 0], [0, 2], [1, 3]];
function linksFor(signal, h) {
  const links = [false, false, false, false];
  if (signal <= 2) return [true, true, true, true];
  if (signal <= 5) { links.fill(true); links[h % 4] = false; return links; }
  if (signal <= 7 && (h >> 3) % 2) { links.fill(true); links[h % 4] = false; return links; }
  for (const side of PAIRS[h % PAIRS.length]) links[side] = true;
  return links;
}

export const AI_MODEL_CARDS = RAW_MODELS.map((m, idx) => {
  const h = hashId(m.id);
  const style = ARCHETYPE_STYLES[m.archetype] || ARCHETYPE_STYLES.transformer;
  const signal = Math.max(1, Math.min(9, m.rarity + 1 + (h % 3) - 1));
  return {
    ...m,
    cardNumber: idx + 1,
    signal,
    mode: modeFor(m),
    echo: echoFor(m, h),
    links: linksFor(signal, h >>> 4),
    color: style.color,
    accent: style.accent,
    archetypeLabel: style.label,
  };
});

